// opentag.v1 is the wire contract every opentag client speaks. This file is the
// write path: how a tag gets raised, where its output is sent, and how the run
// it created is inspected afterwards.
//
// A tag is the only thing the core accepts as work. Every trigger — a Slack
// mention, a GitHub review request, a Jira transition, a cron tick, a raw gRPC
// call — translates its native event into a Tag, and from that point the system
// no longer knows or cares which surface it came from.
//
// Origin and destination are independent, and that independence is the whole
// point of the shape below. Tag.source says where the tag came from; Tag.deliver
// says where its events go, per kind. Neither implies the other, so a tag raised
// in GitHub can deliver into Jira, a cron schedule with no surface at all can
// deliver into both, and a webhook that only wants the outcome can share a run
// with a connector rendering every token.
//
// Field numbering convention, applied in every file of this package: each
// message reserves a trailing range. New fields are carved from the front of
// that range, so two parallel branches cannot pick colliding numbers, and a
// removed field's number is never silently reused.

