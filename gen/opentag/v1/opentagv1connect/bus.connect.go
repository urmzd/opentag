// opentag.v1 is the wire contract every opentag client speaks. This file is the
// read path, and it is the product surface: everything an agent produces leaves
// the system through here.
//
// One stream carries everything. Streaming output, run lifecycle, actions taken
// on a connector's surface, and control-plane changes are all Events on the same
// subscription, distinguished by the kind field. A consumer that wants only
// citations filters for them; it does not subscribe to a second topic and it does
// not have to re-order two streams to reconstruct the conversation.
//
// What deliberately is NOT in the topic namespace, and is a filterable field
// instead:
//
//   kind    all kinds stream the same way; splitting them across topics would
//           force a consumer wanting the whole run to fan in and re-order.
//   rev     canary observation is a filter over one topic, not a topic that
//           blinks into existence each time an agent is revised.
//   origin  where a run came from does not change where its output is read.
//   tenant  an authorization scope carried by the caller's credential, never
//           named by the subscriber (see Event.tenant).
//
// Field numbering convention, applied in every file of this package: each
// message reserves a trailing range. New fields are carved from the front of
// that range, so two parallel branches cannot pick colliding numbers, and a
// removed field's number is never silently reused.

